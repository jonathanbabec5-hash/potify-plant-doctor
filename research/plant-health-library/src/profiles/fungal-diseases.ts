import type { PlantProblemProfile, PlantGroup } from "../schema";

type FungalProfileSpec = {
  id: string;
  name: string;
  affectedPlants: PlantGroup[];
  hosts: string[];
  locations: string[];
  progression: string;
  signs: [string, string];
  conditions: string;
  action: string;
  avoid: string;
  recovery: string;
};

const extensionSource = {
  label: "University of Minnesota Extension — Plant disease diagnosis and management",
  url: "https://extension.umn.edu/plant-diseases",
};

function fungalProfile(spec: FungalProfileSpec): PlantProblemProfile {
  return {
    id: spec.id,
    name: spec.name,
    category: "fungal-disease",
    affectedPlants: spec.affectedPlants,
    specificHosts: spec.hosts,
    growthStages: ["seed-seedling", "vegetative", "flowering", "fruiting", "mature"],
    symptomLocations: spec.locations,
    symptomProgression: spec.progression,
    observableSigns: spec.signs,
    favorableConditions: [
      spec.conditions,
      "Repeated leaf wetness, poor sanitation, and dense foliage can allow fungal inoculum to spread from affected tissue to healthy growth.",
    ],
    lookalikes: [
      {
        condition: "Bacterial leaf spot or blight",
        differentiator:
          "Bacterial lesions are often water-soaked or angular and may produce a yellow halo, while fungal signs more often develop dry margins, concentric growth, or visible spores.",
      },
      {
        condition: "Nutrient stress or chemical injury",
        differentiator:
          "Nutrient or chemical injury usually follows a uniform tissue pattern or application line, while this condition expands as discrete lesions or patches over time.",
      },
    ],
    immediateActions: [
      spec.action,
      "Remove and bag heavily affected plant material, disinfect tools between plants, and improve airflow without handling foliage while it is wet.",
    ],
    treatments: [
      {
        situation: "Low-risk first response",
        treatment:
          "Correct the moisture and sanitation conditions first, then use only a crop- and disease-labeled fungicide if the condition continues to spread and local guidance supports it.",
      },
      {
        situation: "Recurring or high-value plantings",
        treatment:
          "Submit clear photos or a sample to a local extension diagnostic service before rotating treatment modes, because confirmation determines whether a fungicide is useful.",
      },
    ],
    avoid: [
      spec.avoid,
      "Do not compost actively diseased tissue unless the compost system reliably reaches a hot, managed temperature.",
    ],
    recoveryTimeline: spec.recovery,
    prevention: [
      "Water at the root zone early in the day so leaves dry quickly, and space or prune plants to keep air moving through the canopy.",
      "Start each season with clean containers, clean seed or stock, and prompt removal of volunteer plants and infected debris.",
    ],
    monitoringThresholds: [
      "Inspect marked leaves or stems every two to three days; escalate if new lesions continue appearing after moisture control and sanitation changes.",
    ],
    escalationCriteria: [
      "Seek local extension or professional confirmation when the disease reaches new plants, threatens a valuable crop, causes crown or root symptoms, or does not slow within one week.",
    ],
    sources: [extensionSource],
  };
}

